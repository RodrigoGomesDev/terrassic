package com.terrassic.fabric;

import com.terrassic.Terrassic;
import net.fabricmc.api.ModInitializer;
import net.fabricmc.fabric.api.resource.ResourceManagerHelper;
import net.fabricmc.fabric.api.resource.ResourcePackActivationType;
import net.fabricmc.loader.api.FabricLoader;
import net.fabricmc.loader.api.ModContainer;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

public final class TerrassicFabric implements ModInitializer {
    /** Built-in era resource packs, in resourcepacks/<era>/ inside the jar (generated by tools/texpack). */
    private static final String[] ERA_PACKS = {"cretaceo"};
    private static final Logger LOG = LoggerFactory.getLogger("terrassic");

    @Override
    public void onInitialize() {
        // Common setup (registries, spawns). Client renderers are registered from
        // Terrassic.init() through Architectury when running on the client.
        Terrassic.init();
        registerEraPacks();
    }

    /**
     * On by default the first time; if the player turns a pack off, it stays off.
     * In the built jar the pack sits in this mod's own container. In a dev run (runClient) Architectury loads
     * the common module as a separate generated mod, so the pack is looked up in every container that has it.
     */
    private static void registerEraPacks() {
        for (String era : ERA_PACKS) {
            String folder = "resourcepacks/" + era;
            ModContainer mod = findPackOwner(folder + "/pack.mcmeta");
            if (mod == null) {
                LOG.warn("Terrassic: built-in pack {} not found in any mod container", era);
                continue;
            }
            boolean ok = ResourceManagerHelper.registerBuiltinResourcePack(new ResourceLocation(Terrassic.MOD_ID, era),
                    mod, Component.translatable("pack.terrassic." + era), ResourcePackActivationType.DEFAULT_ENABLED);
            if (ok) {
                LOG.info("Terrassic: built-in pack {} registered from mod {}", era, mod.getMetadata().getId());
            } else {
                LOG.warn("Terrassic: built-in pack {} was refused by Fabric (container {}, roots {})", era,
                        mod.getMetadata().getId(), mod.getRootPaths());
            }
        }
    }

    private static ModContainer findPackOwner(String file) {
        ModContainer own = FabricLoader.getInstance().getModContainer(Terrassic.MOD_ID).orElse(null);
        if (own != null && own.findPath(file).isPresent()) {
            return own;
        }
        for (ModContainer c : FabricLoader.getInstance().getAllMods()) {
            if (c.findPath(file).isPresent()) {
                return c;
            }
        }
        return null;
    }
}
