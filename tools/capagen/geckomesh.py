"""
The mod's creatures for the cover scenes, read straight from the files the game loads: the GeckoLib geo.json, the
animation.json and the entity texture in common/src/main/resources/assets/terrassic. A pose is sampled from an animation
at a given time, the cubes are turned into textured quads and placed in the scene at the size the game draws them
(1 block = 16 model units x MODEL_SCALE).

Used for the handmade models (T. rex v2, Pteranodon v3); the older species still come through render3d/voxels.dino_mesh.
"""
import json
import math
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
ASSETS = os.path.join(ROOT, "common", "src", "main", "resources", "assets", "terrassic")
sys.path.insert(0, os.path.join(ROOT, "tools", "modelgen", "handmade", "pteranodon"))

import geo  # noqa: E402  (bone matrices with scale keys, GeckoLib's mirrored x and side-face UVs)
import gl  # noqa: E402

# MODEL_SCALE from the entity classes (generated by gen_species.py)
SCALE = {"tyrannosaurus": 1.02, "pteranodon": 0.8}
HIDE = ("female_display", "saddle")

_cache = {}


def _keys(v, flip):
    if isinstance(v, dict) and not ("post" in v or "vector" in v):
        ks = sorted((float(t), geo._vec(x), isinstance(x, dict) and x.get("lerp_mode") == "linear") for t, x in v.items())
    else:
        ks = [(0.0, geo._vec(v), False)]
    return [(t, flip(x), lin) for t, x, lin in ks]


def _anims(path):
    out = {}
    for name, an in json.load(open(path))["animations"].items():
        bones = {}
        for bn, tr in an.get("bones", {}).items():
            d = {}
            if "rotation" in tr:
                d["rotation"] = _keys(tr["rotation"], lambda x: [-x[0], -x[1], x[2]])
            if "position" in tr:
                d["position"] = _keys(tr["position"], lambda x: [-x[0], x[1], x[2]])
            if "scale" in tr:
                d["scale"] = _keys(tr["scale"], lambda x: x)
            bones[bn] = d
        out[name.split(".")[-1]] = {"length": float(an.get("animation_length", 1.0)), "bones": bones}
    return out


def load(species, sex="male"):
    key = (species, sex)
    if key not in _cache:
        spec = geo.load_geo(os.path.join(ASSETS, "geo", "entity", f"{species}.geo.json"))
        anims = _anims(os.path.join(ASSETS, "animations", "entity", f"{species}.animation.json"))
        tex = Image.open(os.path.join(ASSETS, "textures", "entity", f"{species}_{sex}.png")).convert("RGBA")
        _cache[key] = (spec, anims, tex)
    return _cache[key]


def pose(anims, anim, t):
    """t in 0..1 of the animation's length."""
    an = anims[anim]
    s = t * an["length"]
    out = {}
    for b, tr in an["bones"].items():
        sc = geo.sample(tr["scale"], s) if "scale" in tr else None
        out[b] = (geo.sample(tr.get("rotation", []), s), geo.sample(tr.get("position", []), s), sc)
    return out


def quads(species, anim=None, t=0.0, pos=(0, 0, 0), yaw=0.0, pitch=0.0, roll=0.0, sex="male", size=1.0,
          hidden=HIDE, ground=True):
    """World-space textured quads of a posed creature.

    pos is where the model's feet origin goes (ground=True drops the lowest point onto pos[1]); yaw turns it about
    the vertical axis (0 = facing -Z, the model's forward), pitch tilts the nose up, roll banks it (flyers).
    size multiplies the game size (juveniles, individual variation)."""
    spec, anims, tex = load(species, sex)
    p = pose(anims, anim, t) if anim else None
    F = geo.faces(spec, p, hidden)
    k = SCALE[species] / 16.0 * size
    yw, pt, rl = (math.radians(a) for a in (yaw, pitch, roll))
    Ry = np.array([[math.cos(yw), 0, math.sin(yw)], [0, 1, 0], [-math.sin(yw), 0, math.cos(yw)]])
    Rx = np.array([[1, 0, 0], [0, math.cos(pt), -math.sin(pt)], [0, math.sin(pt), math.cos(pt)]])
    Rz = np.array([[math.cos(rl), -math.sin(rl), 0], [math.sin(rl), math.cos(rl), 0], [0, 0, 1]])
    R = Ry @ Rx @ Rz
    pts = np.array([c for _c, _f, cs, _u in F for c in cs.values()]) * k
    lift = -(pts @ R.T)[:, 1].min() if ground else 0.0
    tw, th = spec["tw"], spec["th"]
    out = []
    for _c, _f, cs, (u0, v0, uw, vh) in F:
        if uw == 0 or vh == 0:
            continue
        order = [(0, 0), (1, 0), (1, 1), (0, 1)]
        w = [R @ (np.array(cs[o]) * k) + np.array(pos) + np.array([0, lift, 0]) for o in order]
        n = np.cross(w[1] - w[0], w[3] - w[0])
        nn = np.linalg.norm(n)
        if nn < 1e-12:
            continue
        n = n / nn
        uvs = [((u0 + o[0] * uw) / tw, (v0 + o[1] * vh) / th) for o in order]
        out += gl.quad_verts([tuple(x) for x in w], uvs, tuple(n), 1.0)
    return np.array(out, np.float32), tex


def mesh(*a, **kw):
    v, tex = quads(*a, **kw)
    return gl.Mesh(v, tex)


def bounds(species, anim=None, t=0.0, **kw):
    v, _ = quads(species, anim, t, **kw)
    return v[:, :3].min(0), v[:, :3].max(0)
