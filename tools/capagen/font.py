def layout(text, gap=1):
    """List of (x, y) filled cells for `text`, and the total (width, height) in cells."""
    cells, x = [], 0
    for ch in text.upper():
        g = GLYPHS[ch]
        for y, row in enumerate(g):
            for dx, c in enumerate(row):
                if c == "#":
                    cells.append((x + dx, y))
        x += len(g[0]) + gap
    return cells, (x - gap, 7)
