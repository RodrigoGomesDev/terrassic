# accented letter -> (base, accent)
COMPOSED = {}
for base, marks in {"a": "àáâãä", "e": "èéêë", "i": "ìíîï", "o": "òóôõö", "u": "ùúûü", "n": "ñ"}.items():
    for ch, mark in zip(marks, ["grave", "acute", "circumflex", "tilde", "diaeresis"] if base in "ao" else
                        (["grave", "acute", "circumflex", "diaeresis"] if base in "eiu" else ["tilde"])):
        COMPOSED[ch] = ("ı" if base == "i" else base, mark)
        COMPOSED[ch.upper()] = (base.upper(), mark)
COMPOSED["ç"] = ("c", "cedilla")
COMPOSED["Ç"] = ("C", "cedilla")
COMPOSED["ý"] = ("y", "acute")
COMPOSED["ÿ"] = ("y", "diaeresis")

