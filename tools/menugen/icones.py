# TerrassicPalette: STONE_200/300/400, AMBER_300/500/700, BASALT_500/600/900/950
STONE_200, STONE_300, STONE_400 = (216, 204, 178), (179, 164, 140), (138, 124, 106)
AMBER_300, AMBER_500, AMBER_700 = (255, 210, 122), (242, 181, 68), (185, 119, 28)
BASALT_500, BASALT_600, BASALT_900, BASALT_950 = (82, 69, 80), (58, 48, 54), (20, 16, 20), (14, 11, 14)

PALETTES = {
    "idle": {"o": STONE_200, "#": STONE_300, "+": STONE_400, "x": BASALT_900},
    "hover": {"o": AMBER_300, "#": AMBER_500, "+": AMBER_700, "x": BASALT_900},
    "dim": {"o": STONE_400, "#": BASALT_500, "+": BASALT_600, "x": BASALT_950},
}
OUTLINE = BASALT_950


def icon(name, state="idle", shadow=True):
    rows = [r for r in ICONS[name].strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows], len(rows))
    pal = PALETTES[state]
    a = np.zeros((16, 16, 4), np.uint8)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in pal:
                a[y, x] = pal[ch] + (255,)
    if shadow:
        # 1 px basalt outline around the drawing (docs/IDENTIDADE.md §3: icons with a dark outline)
        solid = a[:, :, 3] > 0
        ring = np.zeros_like(solid)
        ring[1:] |= solid[:-1]
        ring[:-1] |= solid[1:]
        ring[:, 1:] |= solid[:, :-1]
        ring[:, :-1] |= solid[:, 1:]
        a[ring & ~solid] = OUTLINE + (255,)
    return Image.fromarray(a, "RGBA")


def sheet(path, scale=10):
    names = list(ICONS)
    W = len(names) * 20 + 4
    out = Image.new("RGBA", (W, 44), (26, 26, 27, 255))
    for i, n in enumerate(names):
        for j, st in enumerate(("idle", "hover")):
            out.alpha_composite(icon(n, st), (4 + i * 20, 4 + j * 20))
    out.resize((W * scale, 44 * scale), Image.NEAREST).save(path)



if __name__ == "__main__":
    import sys
    sheet(sys.argv[1] if len(sys.argv) > 1 else "icons_sheet.png")  # preview sheet, 10x
