package com.terrassic.entity.parts;

import com.terrassic.entity.DinosaurEntity;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.network.syncher.SynchedEntityData;
import net.minecraft.server.level.ServerEntity;
import net.minecraft.world.level.Explosion;
import net.minecraft.network.protocol.Packet;
import net.minecraft.network.protocol.game.ClientGamePacketListener;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityDimensions;
import net.minecraft.world.entity.Pose;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.phys.Vec3;

/**
 * One hit part of a creature (1.7, docs/PLANO_PARTES.md): the head, a piece of the neck or of the tail, like the
 * Ender Dragon's. It is never added to the level, saved or sent; it follows its owner every tick and only stands in
 * for it where the game looks for something to hit (the crosshair, arrows, spears, darts). A blow that lands on it is
 * passed to the owner with the part's multiplier: head 125%, neck 100%, tail 75%. The body is the owner's own box.
 *
 * <p>Works the same on Fabric and Forge: Level#getEntities lists the parts and ServerLevel#getEntityOrPart finds them
 * by id (common mixins), so no loader class is needed. Ids are the owner's id + 1..n, reserved when it is created.
 */
public class DinoPart extends Entity {
    /** What part of the body, and how hard a blow there counts. Change the multipliers here only. */
    public enum Kind {
        HEAD(1.25F, 1), NECK(1.0F, 1), TAIL(0.75F, 2), LEGS(0.75F, 0);

        public final float damage;
        /** Where a dart that hits it is drawn (DinosaurEntity#addStuckDart): 0 body, 1 head and neck, 2 tail. */
        public final int zone;

        Kind(float damage, int zone) {
            this.damage = damage;
            this.zone = zone;
        }
    }

    /** A part of a species at size 1: how far in front of the centre (negative = behind), the bottom of the box above
     *  the feet, its width and height, all in blocks. Generated by tools/javagen/parts.py. */
    public record Spec(Kind kind, float forward, float up, float width, float height) {
    }

    public final DinosaurEntity owner;
    public final Spec spec;
    private EntityDimensions size;

    public DinoPart(DinosaurEntity owner, Spec spec) {
        super(owner.getType(), owner.level());
        this.owner = owner;
        this.spec = spec;
        this.size = EntityDimensions.scalable(spec.width(), spec.height());
        this.refreshDimensions();
        this.noPhysics = true;
    }

    public Kind kind() {
        return this.spec.kind();
    }

    /** Resizes the box to the owner's current size (a growing hatchling, a big individual, an alpha). */
    public void resize(float scale) {
        if (Math.abs(this.size.width() - this.spec.width() * scale) > 0.01F) {
            this.size = EntityDimensions.scalable(this.spec.width() * scale, this.spec.height() * scale);
            this.refreshDimensions();
        }
    }

    @Override
    public EntityDimensions getDimensions(Pose pose) {
        return this.size;
    }

    @Override
    protected void defineSynchedData(SynchedEntityData.Builder builder) {
    }

    @Override
    protected void readAdditionalSaveData(CompoundTag tag) {
    }

    @Override
    protected void addAdditionalSaveData(CompoundTag tag) {
    }

    @Override
    public boolean hurt(DamageSource source, float amount) {
        if (this.isInvulnerableTo(source)) {
            return false;
        }
        return this.owner.hurtByPart(this, source, amount);
    }

    @Override
    public boolean is(Entity entity) {
        return this == entity || this.owner == entity;
    }

    @Override
    public boolean isPickable() {
        return this.owner.isPickable() && this.owner.isAlive();
    }

    @Override
    public boolean isAlive() {
        return this.owner.isAlive();
    }

    @Override
    public boolean isSpectator() {
        return this.owner.isSpectator();
    }

    @Override
    public boolean isPushable() {
        return false;
    }

    @Override
    public boolean canBeCollidedWith() {
        return false;
    }

    @Override
    public boolean ignoreExplosion(Explosion explosion) {
        return true;   // the explosion reaches the owner's own box; the parts would only count it again
    }

    @Override
    public boolean shouldBeSaved() {
        return false;
    }

    @Override
    public boolean isAttackable() {
        return this.owner.isAttackable();
    }

    @Override
    public boolean skipAttackInteraction(Entity attacker) {
        return this.owner.skipAttackInteraction(attacker);
    }

    /** A rider does not hit its own mount by the head or the tail, as it does not by the body. */
    @Override
    public Entity getRootVehicle() {
        return this.owner.getRootVehicle();
    }

    @Override
    public void setRemainingFireTicks(int ticks) {
        this.owner.setRemainingFireTicks(ticks);   // a fire-aspect blow on the head sets the creature alight
    }

    @Override
    public InteractionResult interact(Player player, InteractionHand hand) {
        InteractionResult result = this.owner.interact(player, hand);
        if (!result.consumesAction()) {
            ItemStack stack = player.getItemInHand(hand);
            if (!stack.isEmpty()) {
                result = stack.interactLivingEntity(player, this.owner, hand);
            }
        }
        return result;
    }

    @Override
    public InteractionResult interactAt(Player player, Vec3 hit, InteractionHand hand) {
        return this.owner.interactAt(player, hit.add(this.position()).subtract(this.owner.position()), hand);
    }

    @Override
    public ItemStack getPickResult() {
        return this.owner.getPickResult();
    }

    @Override
    public Packet<ClientGamePacketListener> getAddEntityPacket(ServerEntity entity) {
        throw new UnsupportedOperationException("A hit part is never sent: it is rebuilt with its owner");
    }
}
