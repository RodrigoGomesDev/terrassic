/**
 * Velociraptor mongoliensis - fast feathered pack hunter. When one raptor picks a target, the rest of the pack nearby joins in. Leaps at its prey and avoids T. rex.
 *
 * Generated by tools/javagen/gen_species.py - edit the table there.
 */
public class Velociraptor extends PredatorDinosaur {
    /** Hitbox (blocks). Adult real length ~2.0 m. */
    public static final float WIDTH = 0.7F;
    public static final float HEIGHT = 0.9F;
    /** Renderer scale of the GeckoLib model and shadow radius, read by TerrassicClient. */
    public static final float MODEL_SCALE = 0.5F;
    public static final float SHADOW = 0.4F;
    private static final Ingredient FOOD = Ingredient.of(Items.CHICKEN, Items.RABBIT, Items.MUTTON, Items.BEEF, Items.PORKCHOP);
    private static boolean alertingPack;

    public Velociraptor(EntityType<? extends Velociraptor> type, Level level) {
        super(type, level);
        this.xpReward = 8;
    }

    public static AttributeSupplier.Builder createAttributes() {
        return Animal.createMobAttributes()
                .add(Attributes.MAX_HEALTH, 24.0D)
                .add(Attributes.MOVEMENT_SPEED, 0.34D)
                .add(Attributes.ATTACK_DAMAGE, 5.0D)
                .add(Attributes.FOLLOW_RANGE, 24.0D);
    }

    @Override
    public String speciesId() {
        return "velociraptor";
    }

    @Override
    protected Ingredient food() {
        return FOOD;
    }

    @Override
    protected float babyScale() {
        return 0.5F;
    }

    @Override
    protected double cullingInflate() {
        return 1.2D;
    }

    @Override
    protected double runThresholdSqr() {
        return 0.03D;
    }

    @Override
    protected boolean isPrey(LivingEntity e) {
        return e.getBbWidth() < 1.0F && !(e instanceof Velociraptor);
    }

    @Override
    protected int preyInterval() {
        return 80;
    }

    @Override
    protected void addExtraGoals() {
        this.goalSelector.addGoal(2, new LeapAtTargetGoal(this, 0.4F));
        this.goalSelector.addGoal(2, new AvoidEntityGoal<>(this, Tyrannosaurus.class, 14.0F, 1.2D, 1.5D, e -> !this.isTame()));
    }

    @Override
    public void setTarget(LivingEntity target) {
        super.setTarget(target);
        if (target != null && !this.level().isClientSide() && !alertingPack && !this.isTame()) {
            alertingPack = true;
            try {
                for (Velociraptor other : this.level().getEntitiesOfClass(Velociraptor.class, this.getBoundingBox().inflate(16.0D),
                        r -> r != this && r != target && r.getTarget() == null && !r.isBaby() && !r.isTame())) {
                    other.setTarget(target);
                }
            } finally {
                alertingPack = false;
            }
        }
    }

    @Override
    public AgeableMob getBreedOffspring(ServerLevel level, AgeableMob partner) {
        return ModEntities.VELOCIRAPTOR.get().create(level);
    }

    @Override
    protected SoundEvent getAmbientSound() {
        return SoundEvents.FOX_SCREECH;
    }

    @Override
    protected SoundEvent getHurtSound(DamageSource source) {
        return SoundEvents.FOX_HURT;
    }

    @Override
    protected SoundEvent getDeathSound() {
        return SoundEvents.FOX_DEATH;
    }

    @Override
    public float getVoicePitch() {
        return super.getVoicePitch() * 0.8F;
    }

    @Override
    protected float getSoundVolume() {
        return 1.0F;
    }

    @Override
    public int getAmbientSoundInterval() {
        return 200;
    }
}
