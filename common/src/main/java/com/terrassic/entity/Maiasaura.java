/**
 * Maiasaura peeblesorum - the "good mother" hadrosaur. Lives in nesting colonies; babies of any species near an adult grow twice as fast. Rideable when tamed.
 *
 * Generated by tools/javagen/gen_species.py - edit the table there.
 */
public class Maiasaura extends HerbivoreDinosaur {
    /** Hitbox (blocks). Adult real length ~9.0 m. */
    public static final float WIDTH = 2.0F;
    public static final float HEIGHT = 2.8F;
    /** Renderer scale of the GeckoLib model and shadow radius, read by TerrassicClient. */
    public static final float MODEL_SCALE = 0.83F;
    public static final float SHADOW = 1.6F;
    private static final Ingredient FOOD = Ingredient.of(Items.WHEAT, Items.FERN, Items.SWEET_BERRIES);

    public Maiasaura(EntityType<? extends Maiasaura> type, Level level) {
        super(type, level);
        this.xpReward = 12;
    }

    public static AttributeSupplier.Builder createAttributes() {
        return Animal.createMobAttributes()
                .add(Attributes.MAX_HEALTH, 65.0D)
                .add(Attributes.MOVEMENT_SPEED, 0.25D)
                .add(Attributes.ATTACK_DAMAGE, 5.0D)
                .add(Attributes.ARMOR, 3.0D)
                .add(Attributes.KNOCKBACK_RESISTANCE, 0.4D)
                .add(Attributes.FOLLOW_RANGE, 20.0D);
    }

    @Override
    public String speciesId() {
        return "maiasaura";
    }

    @Override
    protected Ingredient food() {
        return FOOD;
    }

    @Override
    protected String[] extraActions() {
        return new String[]{"graze", "call"};
    }

    @Override
    protected float babyScale() {
        return 0.2F;
    }

    @Override
    protected double cullingInflate() {
        return 4.0D;
    }

    @Override
    public boolean isRideable() {
        return true;
    }

    @Override
    protected float riddenSpeedFactor() {
        return 1.05F;
    }

    @Override
    public double getPassengersRidingOffset() {
        return 2.12D * this.getScale();
    }

    @Override
    protected double jumpStrength() {
        return 0.6D;
    }

    @Override
    protected double riderForwardOffset() {
        return 0.66D;
    }

    @Override
    protected double riderReach() {
        return Math.max(super.riderReach(), 4.83D * this.getScale());
    }

    @Override
    public int cargoRows() {
        return 4;
    }

    @Override
    protected int hungerInterval() {
        return 1000;
    }

    @Override
    public boolean hurt(DamageSource source, float amount) {
        boolean hurt = super.hurt(source, amount);
        if (hurt && !this.level().isClientSide() && this.random.nextInt(3) == 0) {
            triggerAnim(ACTION_CONTROLLER, "call");
        }
        return hurt;
    }

    @Override
    public void playAmbientSound() {
        super.playAmbientSound();
        if (!this.level().isClientSide() && this.random.nextInt(3) == 0) {
            triggerAnim(ACTION_CONTROLLER, "call");
        }
    }

    /** "Good mother": every 5 s, babies of any species within 10 blocks of an adult grow 5 s more (2x as fast). */
    @Override
    protected void customServerAiStep() {
        super.customServerAiStep();
        if (!this.isBaby() && this.tickCount % 100 == 0 && this.level() instanceof ServerLevel server) {
            for (DinosaurEntity baby : server.getEntitiesOfClass(DinosaurEntity.class, this.getBoundingBox().inflate(10.0D),
                    DinosaurEntity::isBaby)) {
                baby.ageUp(5);
                server.sendParticles(ParticleTypes.HAPPY_VILLAGER, baby.getX(), baby.getY() + baby.getBbHeight(), baby.getZ(),
                        2, 0.3D, 0.2D, 0.3D, 0.0D);
            }
        }
    }

    @Override
    public AgeableMob getBreedOffspring(ServerLevel level, AgeableMob partner) {
        return ModEntities.MAIASAURA.get().create(level);
    }

    @Override
    protected SoundEvent getAmbientSound() {
        return ModSounds.MAIASAURA_AMBIENT.get();
    }

    @Override
    protected SoundEvent getHurtSound(DamageSource source) {
        return ModSounds.MAIASAURA_HURT.get();
    }

    @Override
    protected SoundEvent getDeathSound() {
        return ModSounds.MAIASAURA_DEATH.get();
    }

    @Override
    public float getVoicePitch() {
        return super.getVoicePitch() * 1.0F;
    }

    @Override
    protected float getSoundVolume() {
        return 1.6F;
    }

    @Override
    public int getAmbientSoundInterval() {
        return 260;
    }
}
