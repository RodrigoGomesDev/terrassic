/**
 * Troodon formosus - 2.4 m gracile troodontid with the biggest eyes of any dinosaur for its size: a nocturnal hunter of small prey that sleeps through the day and wakes at dusk. Avoids the big predators. Only tameable from a stolen wild egg until the knockout (v0.7); a tame one is the night guard: it attacks hostile mobs around it after dark and its owner nearby sees in the dark while it watches.
 *
 * Generated by tools/javagen/gen_species.py - edit the table there.
 */
public class Troodon extends PredatorDinosaur {
    /** Hitbox (blocks). Adult real length ~2.4 m. */
    public static final float WIDTH = 0.6F;
    public static final float HEIGHT = 1.1F;
    /** Renderer scale of the GeckoLib model and shadow radius, read by TerrassicClient. */
    public static final float MODEL_SCALE = 0.55F;
    public static final float SHADOW = 0.4F;
    private static final Ingredient FOOD = Ingredient.of(Items.CHICKEN, Items.RABBIT, Items.EGG, Items.COD, Items.MUTTON);

    public Troodon(EntityType<? extends Troodon> type, Level level) {
        super(type, level);
        this.xpReward = 10;
    }

    public static AttributeSupplier.Builder createAttributes() {
        return Animal.createMobAttributes()
                .add(Attributes.MAX_HEALTH, 20.0D)
                .add(Attributes.MOVEMENT_SPEED, 0.33D)
                .add(Attributes.ATTACK_DAMAGE, 4.0D)
                .add(Attributes.FOLLOW_RANGE, 28.0D);
    }

    @Override
    public String speciesId() {
        return "troodon";
    }

    @Override
    protected Ingredient food() {
        return FOOD;
    }

    @Override
    protected float babyScale() {
        return 0.5F;
    }

    @Override
    protected double cullingInflate() {
        return 1.4D;
    }

    @Override
    protected double runThresholdSqr() {
        return 0.03D;
    }

    @Override
    public int getMaxHeadYRot() {
        return 50;
    }

    @Override
    public int getMaxHeadXRot() {
        return 40;
    }

    @Override
    protected boolean nocturnal() {
        return true;
    }

    @Override
    protected boolean isPrey(LivingEntity e) {
        return e.getBbWidth() < 0.9F && !(e instanceof Troodon);
    }

    @Override
    protected int preyInterval() {
        return 80;
    }

    /** The night guard (docs/GUARDA.md): tame, grown, awake and it is night. */
    private boolean guardsNow() {
        return this.isTame() && !this.isBaby() && !this.isSleeping() && this.level().isNight();
    }

    /** Its owner within twelve blocks sees in the dark while it watches (ambient Night Vision, renewed every two seconds). */
    @Override
    protected void customServerAiStep() {
        super.customServerAiStep();
        if (this.tickCount % 40 == 0 && this.guardsNow() && this.getOwner() instanceof Player owner
                && owner.distanceToSqr(this) < 144.0D) {
            owner.addEffect(new MobEffectInstance(MobEffects.NIGHT_VISION, 300, 0, true, false, true));
        }
    }

    @Override
    protected void addExtraGoals() {
        this.goalSelector.addGoal(2, new LeapAtTargetGoal(this, 0.4F));
        this.targetSelector.addGoal(4, new NearestAttackableTargetGoal<>(this, Monster.class, 10, true, false,
                e -> this.guardsNow() && !this.isInSittingPose() && !(e instanceof Creeper)));
        this.goalSelector.addGoal(2, new AvoidEntityGoal<>(this, PredatorDinosaur.class, 12.0F, 1.2D, 1.5D, e -> !this.isTame() && e.getBbWidth() > 1.5F));
    }

    @Override
    public AgeableMob getBreedOffspring(ServerLevel level, AgeableMob partner) {
        return ModEntities.TROODON.get().create(level);
    }

    @Override
    protected SoundEvent getAmbientSound() {
        return SoundEvents.PARROT_AMBIENT;
    }

    @Override
    protected SoundEvent getHurtSound(DamageSource source) {
        return SoundEvents.FOX_HURT;
    }

    @Override
    protected SoundEvent getDeathSound() {
        return SoundEvents.FOX_DEATH;
    }

    @Override
    public float getVoicePitch() {
        return super.getVoicePitch() * 0.7F;
    }

    @Override
    protected float getSoundVolume() {
        return 0.8F;
    }

    @Override
    public int getAmbientSoundInterval() {
        return 160;
    }

    @Override
    protected void playStepSound(BlockPos pos, BlockState state) {
        this.playSound(SoundEvents.WOLF_STEP, 0.3F, 1.2F);
    }
}
