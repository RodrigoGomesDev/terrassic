    protected boolean isPrey(LivingEntity e) {
        return !(e instanceof Tyrannosaurus) && !(e instanceof Compsognathus) && !(e instanceof Brachiosaurus) && !e.isBaby();
    }

    @Override
    protected int preyInterval() {
        return 200;
    }

    @Override
    public void setTarget(LivingEntity target) {
        LivingEntity previous = this.getTarget();
        super.setTarget(target);
        if (!this.level().isClientSide() && target != null && previous == null && this.displayCooldown <= 0 && !this.isVehicle()) {
            this.displayCooldown = 400;
            triggerAnim(ACTION_CONTROLLER, "roar");
            this.playSound(ModSounds.BOOM_LARGE_THREAT.get(), 3.0F, 1.0F);
        }
    }

    @Override
    protected void customServerAiStep() {
        super.customServerAiStep();
        if (this.displayCooldown > 0) {
            this.displayCooldown--;
        }
    }

    @Override
    public AgeableMob getBreedOffspring(ServerLevel level, AgeableMob partner) {
        return ModEntities.TYRANNOSAURUS.get().create(level);
    }

