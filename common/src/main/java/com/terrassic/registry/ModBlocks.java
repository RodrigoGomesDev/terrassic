package com.terrassic.registry;

import com.terrassic.Terrassic;
import com.terrassic.block.DinoEggBlock;
import com.terrassic.block.ResearchTableBlock;
import com.terrassic.entity.DinosaurEntity;
import dev.architectury.registry.registries.DeferredRegister;
import dev.architectury.registry.registries.RegistrySupplier;
import net.minecraft.core.registries.Registries;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.CarpetBlock;
import net.minecraft.world.level.block.FenceBlock;
import net.minecraft.world.level.block.IronBarsBlock;
import net.minecraft.world.level.block.SlabBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.StairBlock;
import net.minecraft.world.level.block.WallBlock;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.material.MapColor;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.function.Supplier;

/** Dinosaur egg blocks, one per species ("&lt;species&gt;_egg"), and the primitive building blocks. */
public final class ModBlocks {
    public static final DeferredRegister<Block> BLOCKS = DeferredRegister.create(Terrassic.MOD_ID, Registries.BLOCK);

    /** species id -> egg block, in registration order (also used for the creative tab). */
    public static final Map<String, RegistrySupplier<Block>> EGGS = new LinkedHashMap<>();

    static {
        egg("tyrannosaurus", ModEntities.TYRANNOSAURUS, true);
        egg("spinosaurus", ModEntities.SPINOSAURUS, true);
        egg("dilophosaurus", ModEntities.DILOPHOSAURUS, false);
        egg("velociraptor", ModEntities.VELOCIRAPTOR, false);
        egg("compsognathus", ModEntities.COMPSOGNATHUS, false);
        egg("triceratops", ModEntities.TRICERATOPS, true);
        egg("stegosaurus", ModEntities.STEGOSAURUS, true);
        egg("ankylosaurus", ModEntities.ANKYLOSAURUS, true);
        egg("brachiosaurus", ModEntities.BRACHIOSAURUS, true);
        egg("parasaurolophus", ModEntities.PARASAUROLOPHUS, true);
        egg("pachycephalosaurus", ModEntities.PACHYCEPHALOSAURUS, false);
        egg("gallimimus", ModEntities.GALLIMIMUS, false);
        egg("maiasaura", ModEntities.MAIASAURA, false);
        egg("pteranodon", ModEntities.PTERANODON, false);
    }

    // ---- primitive building blocks (resources generated by tools/javagen/gen_blocks.py, same ids)

    /** building block id -> block, in creative-tab order. */
    public static final Map<String, RegistrySupplier<Block>> BUILDING = new LinkedHashMap<>();

    public static final RegistrySupplier<Block> THATCH = building("thatch",
            () -> new Block(thatch()));
    public static final RegistrySupplier<Block> THATCH_STAIRS = building("thatch_stairs",
            () -> new StairBlock(THATCH.get().defaultBlockState(), thatch()) {});
    public static final RegistrySupplier<Block> THATCH_SLAB = building("thatch_slab",
            () -> new SlabBlock(thatch()));
    public static final RegistrySupplier<Block> STRAW_MAT = building("straw_mat",
            () -> new CarpetBlock(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_YELLOW).strength(0.1F)
                    .sound(SoundType.GRASS).ignitedByLava()) {});
    public static final RegistrySupplier<Block> WATTLE_AND_DAUB = building("wattle_and_daub",
            () -> new Block(BlockBehaviour.Properties.of().mapColor(MapColor.DIRT).strength(1.2F, 3.0F)
                    .sound(SoundType.MUD_BRICKS)));
    public static final RegistrySupplier<Block> LOG_PALISADE = building("log_palisade",
            () -> new Block(BlockBehaviour.Properties.of().mapColor(MapColor.PODZOL).strength(2.5F, 4.0F)
                    .sound(SoundType.WOOD).ignitedByLava().noOcclusion()));
    public static final RegistrySupplier<Block> DRY_STONE = building("dry_stone",
            () -> new Block(dryStone()));
    public static final RegistrySupplier<Block> DRY_STONE_STAIRS = building("dry_stone_stairs",
            () -> new StairBlock(DRY_STONE.get().defaultBlockState(), dryStone()) {});
    public static final RegistrySupplier<Block> DRY_STONE_SLAB = building("dry_stone_slab",
            () -> new SlabBlock(dryStone()));
    public static final RegistrySupplier<Block> DRY_STONE_WALL = building("dry_stone_wall",
            () -> new WallBlock(dryStone().forceSolidOn()));
    public static final RegistrySupplier<Block> BONE_FENCE = building("bone_fence",
            () -> new FenceBlock(BlockBehaviour.Properties.of().mapColor(MapColor.SAND).strength(2.0F)
                    .requiresCorrectToolForDrops().sound(SoundType.BONE_BLOCK).forceSolidOn()));
    public static final RegistrySupplier<Block> HIDE_SCREEN = building("hide_screen",
            () -> new IronBarsBlock(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_BROWN).strength(0.8F)
                    .sound(SoundType.WOOL).ignitedByLava().noOcclusion()) {});
    public static final RegistrySupplier<Block> FUR_RUG = building("fur_rug",
            () -> new CarpetBlock(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_BROWN).strength(0.1F)
                    .sound(SoundType.WOOL).ignitedByLava()) {});

    // ---- science (items registered in ModItems)

    /** Stone with fossil bones in it. Mined with a pickaxe it only gives cobblestone and bones; a Hair Brush or a
     *  Flint Chisel digs the fossil out (ExcavationToolItem). Generated underground by worldgen. */
    public static final RegistrySupplier<Block> FOSSIL_ROCK = BLOCKS.register("fossil_rock",
            () -> new Block(BlockBehaviour.Properties.of().mapColor(MapColor.STONE).strength(2.0F, 6.0F)
                    .requiresCorrectToolForDrops().sound(SoundType.STONE)));
    public static final RegistrySupplier<Block> RESEARCH_TABLE = BLOCKS.register("research_table",
            () -> new ResearchTableBlock(BlockBehaviour.Properties.of().mapColor(MapColor.STONE).strength(2.0F, 6.0F)
                    .sound(SoundType.STONE).noOcclusion()));

    private ModBlocks() {
    }

    private static void egg(String species, RegistrySupplier<? extends EntityType<? extends DinosaurEntity>> type, boolean large) {
        EGGS.put(species, BLOCKS.register(species + "_egg", () -> new DinoEggBlock(type, large,
                BlockBehaviour.Properties.of().mapColor(MapColor.SAND).strength(0.5F).sound(SoundType.METAL)
                        .randomTicks().noOcclusion())));
    }

    private static RegistrySupplier<Block> building(String id, Supplier<Block> block) {
        RegistrySupplier<Block> reg = BLOCKS.register(id, block);
        BUILDING.put(id, reg);
        return reg;
    }

    private static BlockBehaviour.Properties thatch() {
        return BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_YELLOW).strength(0.5F).sound(SoundType.GRASS).ignitedByLava();
    }

    private static BlockBehaviour.Properties dryStone() {
        return BlockBehaviour.Properties.of().mapColor(MapColor.STONE).strength(1.5F, 6.0F).requiresCorrectToolForDrops();
    }

    /** The egg block of a species, or null if the registry is not ready / unknown species. */
    public static Block eggFor(String species) {
        RegistrySupplier<Block> egg = EGGS.get(species);
        return egg != null && egg.isPresent() ? egg.get() : null;
    }
}
