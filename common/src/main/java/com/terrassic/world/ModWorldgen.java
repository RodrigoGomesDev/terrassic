package com.terrassic.world;

import com.terrassic.config.Story;
import com.terrassic.Terrassic;
import com.terrassic.registry.BuildingBlocks;
import com.terrassic.registry.ModItems;
import dev.architectury.event.events.common.LifecycleEvent;
import dev.architectury.event.events.common.LootEvent;
import dev.architectury.registry.level.biome.BiomeModifications;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.BiomeTags;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.levelgen.GenerationStep;
import net.minecraft.world.level.levelgen.placement.PlacedFeature;
import net.minecraft.world.level.storage.loot.LootPool;
import net.minecraft.world.level.storage.loot.entries.LootItem;
import net.minecraft.world.level.storage.loot.predicates.LootItemRandomChanceCondition;
import net.minecraft.world.level.storage.loot.providers.number.ConstantValue;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * World generation and loot:
 * <ul>
 *   <li>Rock veins and pebble patches of the building blocks (BuildingBlocks.FEATURES, generated by
 *       tools/javagen/gen_blocks.py).</li>
 *   <li>Fossil rock veins in every overworld biome (data/terrassic/worldgen/{configured,placed}_feature/fossil_rock.json,
 *       generated by tools/javagen/gen_resources.py).</li>
 *   <li>Loose pages of Katarina's notebook in some vanilla chests, only with the story mode on (config/Story).</li>
 * </ul>
 */
public final class ModWorldgen {
    public static final ResourceKey<PlacedFeature> FOSSIL_ROCK =
            ResourceKey.create(Registries.PLACED_FEATURE, Terrassic.id("fossil_rock"));

    /** Vanilla chest -> chance of one loose page. */
    private static final Map<ResourceLocation, Float> PAGE_CHESTS = Map.of(
            new ResourceLocation("chests/simple_dungeon"), 0.5F,
            new ResourceLocation("chests/abandoned_mineshaft"), 0.25F,
            new ResourceLocation("chests/desert_pyramid"), 0.5F,
            new ResourceLocation("chests/jungle_temple"), 0.5F,
            new ResourceLocation("chests/shipwreck_map"), 0.4F,
            new ResourceLocation("chests/buried_treasure"), 0.6F,
            new ResourceLocation("chests/ruined_portal"), 0.3F,
            new ResourceLocation("chests/village/village_cartographer"), 0.5F,
            new ResourceLocation("chests/igloo_chest"), 0.5F);

    private ModWorldgen() {
    }

    public static void init() {
        LifecycleEvent.SETUP.register(() -> BiomeModifications.addProperties(
                ctx -> ctx.hasTag(BiomeTags.IS_OVERWORLD),
                (ctx, props) -> props.getGenerationProperties().addFeature(GenerationStep.Decoration.UNDERGROUND_ORES, FOSSIL_ROCK)));
        // rock veins and pebble patches of the building blocks, generated by gen_blocks.py.
        // ONE modification per feature, with all its biome tags together: a biome that is in two of the tags
        // (Terralith's yosemite_lowlands is both #is_forest and #is_taiga) would otherwise get the same feature twice,
        // and Minecraft refuses to create the world with "Feature order cycle found".
        LifecycleEvent.SETUP.register(() -> {
            Map<String, List<String[]>> byFeature = new LinkedHashMap<>();
            for (String[] f : BuildingBlocks.FEATURES) {
                byFeature.computeIfAbsent(f[0], k -> new ArrayList<>()).add(f);
            }
            for (List<String[]> rows : byFeature.values()) {
                ResourceKey<PlacedFeature> feature = ResourceKey.create(Registries.PLACED_FEATURE, Terrassic.id(rows.get(0)[0]));
                GenerationStep.Decoration step = GenerationStep.Decoration.valueOf(rows.get(0)[1].toUpperCase(java.util.Locale.ROOT));
                List<TagKey<Biome>> tags = new ArrayList<>();
                for (String[] r : rows) {
                    tags.add(TagKey.create(Registries.BIOME, new ResourceLocation(r[2])));
                }
                BiomeModifications.addProperties(ctx -> {
                            for (TagKey<Biome> tag : tags) {
                                if (ctx.hasTag(tag)) {
                                    return true;
                                }
                            }
                            return false;
                        },
                        (ctx, props) -> props.getGenerationProperties().addFeature(step, feature));
            }
        });

        LootEvent.MODIFY_LOOT_TABLE.register((lootTables, id, context, builtin) -> {
            Float chance = PAGE_CHESTS.get(id);
            if (builtin && chance != null && Story.enabled()) {
                context.addPool(LootPool.lootPool()
                        .setRolls(ConstantValue.exactly(1.0F))
                        .add(LootItem.lootTableItem(ModItems.LOOSE_PAGE.get()))
                        .when(LootItemRandomChanceCondition.randomChance(chance))
                        .build());
            }
        });
    }
}
