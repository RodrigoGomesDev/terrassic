package com.terrassic.world;

import com.terrassic.Terrassic;
import dev.architectury.event.EventResult;
import dev.architectury.event.events.common.EntityEvent;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.tags.TagKey;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.Mob;
import net.minecraft.world.entity.MobCategory;
import net.minecraft.world.entity.MobSpawnType;
import net.minecraft.world.entity.animal.horse.SkeletonHorse;
import net.minecraft.world.entity.monster.AbstractSkeleton;
import net.minecraft.world.entity.monster.Drowned;
import net.minecraft.world.entity.monster.Phantom;
import net.minecraft.world.entity.monster.Witch;
import net.minecraft.world.entity.monster.Zombie;
import net.minecraft.world.entity.monster.ZombieVillager;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.LevelAccessor;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.levelgen.Heightmap;

import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * The 11 biomes of the Late Cretaceous (v0.8, "Mundo Terrassic"). They exist only in worlds created with the world
 * type "Terrassic" (data/terrassic/worldgen/world_preset). Everything about them is data generated by
 * tools/javagen/gen_world.py: the biome JSONs (plants, trees, colours, vanilla mobs), the world presets with the biome
 * map, and the biome tags. The surface blocks come from {@link CretaceousSurface}.
 *
 * <p>Dinosaurs reach these biomes through ModSpawns: every biome predicate there also checks
 * {@code terrassic:habitat/<word>} (forest, river, savanna...), so a species added to the WORLD table of
 * gen_species.py spawns here without touching this class.
 *
 * <p>Here: the vanilla creatures that do not belong to the era (see {@link #blocksSpawn}). In Cretaceous biomes
 * zombies and skeletons only spawn below the surface (caves keep their monsters and drops), and witches, zombie
 * villagers, drowned and phantoms never spawn naturally. No vanilla animal spawns there at all (docs/MUNDO.md, section
 * 10.4): the biome JSONs list none, and anything another source would add (a mod, a data pack, the skeleton horse
 * trap of a thunderstorm) is refused too; food and resources come from the prehistoric fauna. Spawners in monster
 * rooms and spawn eggs are left alone.
 */
public final class CretaceousBiomes {
    public static final ResourceKey<Biome> HADROSAUR_PLAINS = key("hadrosaur_plains");
    public static final ResourceKey<Biome> MAGNOLIA_FOREST = key("magnolia_forest");
    public static final ResourceKey<Biome> CYPRESS_SWAMP = key("cypress_swamp");
    public static final ResourceKey<Biome> REDWOOD_FOREST = key("redwood_forest");
    public static final ResourceKey<Biome> DRY_LANDS = key("dry_lands");
    public static final ResourceKey<Biome> RIVER_DELTA = key("river_delta");
    public static final ResourceKey<Biome> INNER_SEA = key("inner_sea");
    public static final ResourceKey<Biome> DEEP_INNER_SEA = key("deep_inner_sea");
    public static final ResourceKey<Biome> RIVER = key("cretaceous_river");
    public static final ResourceKey<Biome> BEACH = key("cretaceous_beach");
    public static final ResourceKey<Biome> HIGHLANDS = key("cretaceous_highlands");

    /** All the biomes above. */
    public static final TagKey<Biome> CRETACEOUS = TagKey.create(Registries.BIOME, Terrassic.id("cretaceous"));

    private static final Map<String, TagKey<Biome>> HABITATS = new ConcurrentHashMap<>();

    private CretaceousBiomes() {
    }

    private static ResourceKey<Biome> key(String id) {
        return ResourceKey.create(Registries.BIOME, Terrassic.id(id));
    }

    /** {@code terrassic:habitat/<word>}: the Cretaceous biomes where the species of that WORLD word spawn. */
    public static TagKey<Biome> habitat(String word) {
        return HABITATS.computeIfAbsent(word, w -> TagKey.create(Registries.BIOME, Terrassic.id("habitat/" + w)));
    }

    public static void init() {
        EntityEvent.ADD.register(CretaceousBiomes::onAdd);
    }

    /**
     * Called by MobMixin from Mob.checkSpawnRules for natural and world-generation spawns: in Cretaceous biomes,
     * zombies and skeletons only spawn below the surface (caves keep their monsters and drops), and witches, zombie
     * villagers and drowned never spawn. (Architectury's LIVING_CHECK_SPAWN can't be used to deny a spawn: Forge and
     * Fabric read its result the opposite way.)
     */
    public static boolean blocksSpawn(Mob mob, LevelAccessor level, MobSpawnType type) {
        if (type != MobSpawnType.NATURAL && type != MobSpawnType.CHUNK_GENERATION) {
            return false;
        }
        if (isVanillaAnimal(mob)) {
            return level.getBiome(mob.blockPosition()).is(CRETACEOUS);
        }
        boolean never = mob instanceof Witch || mob instanceof ZombieVillager || mob instanceof Drowned;
        boolean blockedOnSurface = mob instanceof Zombie || mob instanceof AbstractSkeleton;
        if (!never && !blockedOnSurface) {
            return false;
        }
        BlockPos pos = mob.blockPosition();
        if (!level.getBiome(pos).is(CRETACEOUS)) {
            return false;
        }
        // "surface" = at the top of the column, ignoring leaves (a forest floor at night counts as surface too)
        return never || pos.getY() >= level.getHeight(Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, pos.getX(), pos.getZ()) - 2;
    }

    /** Any creature of vanilla Minecraft that is not a monster: animals, fish, squids, bats, villagers... */
    private static boolean isVanillaAnimal(Entity entity) {
        return entity.getType().getCategory() != MobCategory.MONSTER
                && "minecraft".equals(BuiltInRegistries.ENTITY_TYPE.getKey(entity.getType()).getNamespace());
    }

    /**
     * Phantoms and the skeleton horse trap of thunderstorms don't go through spawn rules (they are added directly):
     * keep them out of the Cretaceous.
     */
    private static EventResult onAdd(Entity entity, Level level) {
        boolean outOfEra = entity instanceof Phantom || entity instanceof SkeletonHorse horse && horse.isTrap();
        if (outOfEra && !level.isClientSide && level.getBiome(entity.blockPosition()).is(CRETACEOUS)) {
            return EventResult.interruptFalse();
        }
        return EventResult.pass();
    }
}
