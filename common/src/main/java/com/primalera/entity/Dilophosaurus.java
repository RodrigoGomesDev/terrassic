/**
 * Dilophosaurus wetherilli - mid-sized Jurassic predator with a pair of thin head crests. Flashes its crests before attacking.
 *
 * Generated by tools/javagen/gen_species.py - edit the table there.
 */
public class Dilophosaurus extends PredatorDinosaur {
    private static final Ingredient FOOD = Ingredient.of(Items.CHICKEN, Items.RABBIT, Items.MUTTON, Items.PORKCHOP);
    private int displayCooldown;

    public Dilophosaurus(EntityType<? extends Dilophosaurus> type, Level level) {
        super(type, level);
        this.setMaxUpStep(1.0F);
        this.xpReward = 12;
    }

    public static AttributeSupplier.Builder createAttributes() {
        return Animal.createMobAttributes()
                .add(Attributes.MAX_HEALTH, 40.0D)
                .add(Attributes.MOVEMENT_SPEED, 0.3D)
                .add(Attributes.ATTACK_DAMAGE, 7.0D)
                .add(Attributes.FOLLOW_RANGE, 24.0D)
                .add(Attributes.ARMOR, 2.0D);
    }

    @Override
    public String speciesId() {
        return "dilophosaurus";
    }

    @Override
    protected Ingredient food() {
        return FOOD;
    }

    @Override
    protected String[] extraActions() {
        return new String[]{"display"};
    }

    @Override
    protected double cullingInflate() {
        return 1.5D;
    }

    @Override
    public int getMaxHeadYRot() {
        return 45;
    }

    @Override
    public int getMaxHeadXRot() {
        return 30;
    }

    @Override
    protected boolean isPrey(LivingEntity e) {
        return e.getBbWidth() < 1.0F && !(e instanceof DinosaurEntity);
    }

    @Override
    protected int preyInterval() {
        return 100;
    }

    @Override
    public void setTarget(LivingEntity target) {
        LivingEntity previous = this.getTarget();
        super.setTarget(target);
        if (!this.level().isClientSide() && target != null && previous == null && this.displayCooldown <= 0 && !this.isVehicle()) {
            this.displayCooldown = 400;
            triggerAnim(ACTION_CONTROLLER, "display");
            this.playSound(SoundEvents.HOGLIN_ANGRY, 1.2F, 1.3F);
        }
    }

    @Override
    protected void customServerAiStep() {
        super.customServerAiStep();
        if (this.displayCooldown > 0) {
            this.displayCooldown--;
        }
    }

    @Override
    public AgeableMob getBreedOffspring(ServerLevel level, AgeableMob partner) {
        return ModEntities.DILOPHOSAURUS.get().create(level);
    }

    @Override
    protected SoundEvent getAmbientSound() {
        return SoundEvents.HOGLIN_AMBIENT;
    }

    @Override
    protected SoundEvent getHurtSound(DamageSource source) {
        return SoundEvents.HOGLIN_HURT;
    }

    @Override
    protected SoundEvent getDeathSound() {
        return SoundEvents.HOGLIN_DEATH;
    }

    @Override
    public float getVoicePitch() {
        return super.getVoicePitch() * 1.25F;
    }

    @Override
    protected float getSoundVolume() {
        return 1.2F;
    }

    @Override
    public int getAmbientSoundInterval() {
        return 220;
    }
}
