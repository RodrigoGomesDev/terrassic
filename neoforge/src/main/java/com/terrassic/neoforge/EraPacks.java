package com.terrassic.neoforge;

import com.terrassic.Terrassic;
import net.minecraft.network.chat.Component;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackSelectionConfig;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.PathPackResources;
import net.minecraft.server.packs.repository.Pack;
import net.minecraft.server.packs.repository.PackSource;
import net.neoforged.fml.ModList;
import net.neoforged.neoforge.event.AddPackFindersEvent;
import net.neoforged.neoforgespi.language.IModFileInfo;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Optional;

/**
 * Built-in era resource packs (resourcepacks/<era>/ inside the jar, generated by tools/texpack).
 * The pack can be turned off by the player, so it is not "required": {@link EraPacksClient} switches it on once.
 * CLIENT_RESOURCES is only asked for on the client, so the client-only class never loads on a server.
 */
final class EraPacks {
    private static final Logger LOG = LoggerFactory.getLogger("terrassic");
    private static final String[] ERA_PACKS = {"cretaceo"};

    private EraPacks() {
    }

    static void onAddPackFinders(AddPackFindersEvent event) {
        if (event.getPackType() != PackType.CLIENT_RESOURCES) {
            return;
        }
        for (String era : ERA_PACKS) {
            Path path = findPack("resourcepacks/" + era);
            if (path == null) {
                LOG.warn("Terrassic: built-in pack {} not found in any mod file", era);
                continue;
            }
            String id = Terrassic.MOD_ID + "_" + era;
            PackLocationInfo info = new PackLocationInfo(id, Component.translatable("pack.terrassic." + era),
                    PackSource.BUILT_IN, Optional.empty());
            Pack pack = Pack.readMetaAndCreate(info, new PathPackResources.PathResourcesSupplier(path),
                    PackType.CLIENT_RESOURCES, new PackSelectionConfig(false, Pack.Position.TOP, false));
            if (pack == null) {
                LOG.warn("Terrassic: built-in pack {} has no readable pack.mcmeta at {}", era, path);
                continue;
            }
            LOG.info("Terrassic: built-in pack {} registered from {}", era, path);
            event.addRepositorySource(consumer -> consumer.accept(pack));
            EraPacksClient.enableOnce(id);
        }
    }

    /** This mod's own file first; in a dev run the common module may be a file of its own, so look in all. */
    private static Path findPack(String folder) {
        Path own = ModList.get().getModFileById(Terrassic.MOD_ID).getFile().findResource(folder);
        if (Files.exists(own.resolve("pack.mcmeta"))) {
            return own;
        }
        for (IModFileInfo info : ModList.get().getModFiles()) {
            Path p = info.getFile().findResource(folder);
            if (Files.exists(p.resolve("pack.mcmeta"))) {
                return p;
            }
        }
        return null;
    }
}
